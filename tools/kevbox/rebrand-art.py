#!/usr/bin/env python3
"""Override every OwnTV brand drawable from Core with KevBox Live art.

KevBox Live fork only: this file does not exist upstream (ahXN00/OwnTV).

Core ships the logo, launcher icons, TV banners, splash art and wordmark as library resources. An
app resource of the same name, type and qualifier replaces the library's, so the manifest, the
launch themes and BrandLockup.kt keep their references and pick up the new art without an edit.

    python3 tools/kevbox/rebrand-art.py            # regenerate every override from the masters
    python3 tools/kevbox/rebrand-art.py --check    # exit 1 if a Core brand file lacks an override
    python3 tools/kevbox/rebrand-art.py --masters  # rebuild the masters from the real logo first

The masters live in tools/kevbox/art/. --masters rebuilds them from the KevBox logo
(kevbox-support/public/Logo/KEVbox.png) and Poppins Bold: the logo pixels always come from that
file, and the "LIVE" badge is drawn here. Every step is plain Pillow, so the output is the same
on every run.

What each Core file becomes:
- A raster (icon foregrounds, banners, splash names): a PNG of the same name at the same
  qualifier and the exact same pixel size.
- A drawable the framework reads (splash icons, notification icon, monochrome icon): an XML of
  the same name in drawable/ that wraps drawable-nodpi/kevbox_<name>.png in a <bitmap>, so the
  raster is never read as mdpi and scaled.
- A drawable that Compose draws with painterResource (marks, small marks, wordmarks): a PNG of
  the same name in drawable/. painterResource only takes vector XML or a raster file and throws
  on a <bitmap> XML, so these cannot use the wrapper.
- owntv_mark_play and owntv_mark_play_small: an empty vector, because BrandMark tints them over
  the mark and the KevBox mark has no play triangle.
- The adaptive icons in mipmap-anydpi-v26: a white background layer, the KevBox foreground and
  the KevBox monochrome silhouette.

Rerun after a Core bump; an unknown brand file name makes the script stop rather than guess.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
from core_res import core_pin, core_res_dir  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
RES = REPO / "app" / "src" / "main" / "res"
ART = REPO / "tools" / "kevbox" / "art"
LOGO = Path("/home/kevin/projects/kevbox-support/public/Logo/KEVbox.png")
FONT = RES / "font" / "poppins_bold.ttf"

MARK = ART / "kevbox_live_mark.png"
BANNER = ART / "kevbox_live_banner.png"
WORDMARK_KEVBOX = ART / "kevbox_live_wordmark_kevbox.png"
WORDMARK_LIVE = ART / "kevbox_live_wordmark_live.png"
SPLASH_NAME = ART / "kevbox_live_splash_name.png"

# The logo's two parts inside KEVbox.png (9332 x 5200): the cube with "KEV", and "BOX".
LOGO_BOX = (1378, 1261, 7731, 3870)
CUBE_RIGHT = 3743
BOX_LETTERS_TOP, BOX_LETTERS_BOTTOM = 1693, 3257

LOGO_BLUE = (32, 58, 209)
LIVE_RED = (229, 37, 44)
WHITE = (255, 255, 255)

# Core's wordmark drawing is 988 x 182; BrandLockup.kt draws both halves into that box.
WORDMARK_SIZE = (988, 182)

# Sizes for the drawables Core only has as vectors. Files in drawable/ are read as mdpi, so these
# are scaled up by the screen density when decoded: 192 px is 384 px on an xhdpi TV.
MARK_PX = 192
MARK_SMALL_PX = 64
WORDMARK_PX = (494, 91)
SPLASH_ICON_PX = 432
NOTIFICATION_PX = 96
MONOCHROME_PX = 432

# How much of a square canvas the mark master fills. Adaptive icons show the central 66 of 108 dp
# through a circle; the Android 12 splash icon shows the central two thirds of its view.
ICON_SCALE = 0.62
SPLASH_SCALE = 0.50
NOTIFICATION_SCALE = 0.94

BRAND_NAME = re.compile(r"^owntv_(icon_|banner_|splash_|mark_|wordmark_|notification$)")
VECTOR_SIZE = re.compile(r'android:(width|height|viewportWidth|viewportHeight)="([^"]+)"')

GENERATED_NOTE = (
    "<!-- KevBox Live fork only: generated by tools/kevbox/rebrand-art.py. {what} -->"
)


# ---------------------------------------------------------------------------------------------
# Image helpers


def resize(img: Image.Image, size: tuple[int, int]) -> Image.Image:
    return img.resize(size, Image.Resampling.LANCZOS)


def fit_into(img: Image.Image, size: tuple[int, int], scale: float = 1.0) -> Image.Image:
    """Centre img on a transparent canvas of size, as large as fits inside scale x the canvas."""
    w, h = size
    box_w, box_h = w * scale, h * scale
    ratio = min(box_w / img.width, box_h / img.height)
    inner = resize(img, (max(1, round(img.width * ratio)), max(1, round(img.height * ratio))))
    canvas = Image.new("RGBA", size, (0, 0, 0, 0))
    canvas.alpha_composite(inner, ((w - inner.width) // 2, (h - inner.height) // 2))
    return canvas


def recolor(img: Image.Image, rgb: tuple[int, int, int]) -> Image.Image:
    """Keep img's alpha, paint every pixel rgb."""
    out = Image.new("RGBA", img.size, rgb + (0,))
    out.putalpha(img.getchannel("A"))
    return out


def silhouette(mark: Image.Image) -> Image.Image:
    """White, alpha-only shape of the mark's ink: the blue logo and the red badge.

    The mark is a white card, so ink is whatever is darker than white; the card itself, the "KEV"
    letters cut out of the cube and the white "LIVE" text drop out.
    """
    px = np.asarray(mark.convert("RGBA")).astype(np.float64)
    darkest = px[:, :, :3].min(axis=2)
    ink = np.clip((255.0 - darkest) / (255.0 - 40.0), 0.0, 1.0)
    alpha = np.rint(ink * px[:, :, 3]).astype(np.uint8)
    out = Image.new("RGBA", mark.size, WHITE + (0,))
    out.putalpha(Image.fromarray(alpha, "L"))
    return out


def save_png(img: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "PNG", optimize=True)


# ---------------------------------------------------------------------------------------------
# Masters


def font(size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(str(FONT), size)


def live_badge(height: int) -> Image.Image:
    """A red pill with white "LIVE", drawn at 4x and scaled down for smooth edges."""
    s = 4
    h = height * s
    f = font(round(h * 0.56))
    left, top, right, bottom = f.getbbox("LIVE", anchor="ls")
    text_w = right - left
    w = round(text_w + h * 0.95)
    big = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(big)
    draw.rounded_rectangle((0, 0, w - 1, h - 1), radius=h // 2, fill=LIVE_RED + (255,))
    cap = -top
    baseline = (h + cap) // 2
    draw.text(((w - text_w) // 2 - left, baseline), "LIVE", font=f, fill=WHITE + (255,), anchor="ls")
    return resize(big, (round(w / s), height))


def load_logo() -> tuple[Image.Image, Image.Image]:
    """The whole logo and the cube alone, cropped from KEVbox.png."""
    if not LOGO.is_file():
        sys.exit(f"rebrand-art: the KevBox logo is missing: {LOGO}")
    src = Image.open(LOGO).convert("RGBA")
    logo = src.crop(LOGO_BOX)
    cube = src.crop((LOGO_BOX[0], LOGO_BOX[1], CUBE_RIGHT, LOGO_BOX[3]))
    return logo, cube


def build_mark_master(cube: Image.Image) -> Image.Image:
    """Square: a white rounded card, the cube, and the LIVE badge under it."""
    size = 2048
    card = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(card).rounded_rectangle(
        (0, 0, size - 1, size - 1), radius=round(size * 0.22), fill=WHITE + (255,)
    )
    cube_h = round(size * 0.56)
    cube_img = resize(cube, (round(cube.width * cube_h / cube.height), cube_h))
    badge = live_badge(round(size * 0.17))
    gap = round(size * 0.04)
    top = (size - (cube_h + gap + badge.height)) // 2
    card.alpha_composite(cube_img, ((size - cube_img.width) // 2, top))
    card.alpha_composite(badge, ((size - badge.width) // 2, top + cube_h + gap))
    return resize(card, (1024, 1024))


def build_banner_master(logo: Image.Image) -> Image.Image:
    """16:9 TV banner: the logo on a light backdrop, the LIVE badge under "BOX"."""
    w, h = 1920, 1080
    top_rgb, bottom_rgb = np.array([255, 255, 255]), np.array([232, 236, 250])
    t = np.linspace(0.0, 1.0, h)[:, None, None]
    rows = np.rint(top_rgb * (1 - t) + bottom_rgb * t).astype(np.uint8)
    banner = Image.fromarray(np.repeat(rows, w, axis=1), "RGB").convert("RGBA")
    logo_w = round(w * 0.74)
    logo_img = resize(logo, (logo_w, round(logo.height * logo_w / logo.width)))
    badge = live_badge(round(h * 0.19))
    gap = round(h * 0.045)
    top = (h - (logo_img.height + gap + badge.height)) // 2
    left = (w - logo_w) // 2
    banner.alpha_composite(logo_img, (left, top))
    banner.alpha_composite(badge, (left + logo_w - badge.width, top + logo_img.height + gap))
    return banner.convert("RGB")


def build_splash_name_master(logo: Image.Image) -> Image.Image:
    """2.5:1, for the dark launch screen: the logo in white beside the LIVE badge."""
    w, h = 1000, 400
    canvas = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    logo_h = round(h * 0.55)
    logo_img = recolor(resize(logo, (round(logo.width * logo_h / logo.height), logo_h)), WHITE)
    badge = live_badge(round(h * 0.32))
    gap = round(h * 0.09)
    left = (w - (logo_img.width + gap + badge.width)) // 2
    canvas.alpha_composite(logo_img, (left, (h - logo_h) // 2))
    canvas.alpha_composite(badge, (left + logo_img.width + gap, (h - badge.height) // 2))
    return canvas


def build_wordmark_masters(logo: Image.Image) -> tuple[Image.Image, Image.Image]:
    """Alpha masks in Core's 988 x 182 box (at 2x): the logo as "KevBox", then "LIVE".

    BrandLockup.kt tints each half with one colour, so both are white shapes on transparent. LIVE
    takes the height of the logo's "BOX" letters and sits on their baseline.
    """
    s = 2
    box_w, box_h = WORDMARK_SIZE[0] * s, WORDMARK_SIZE[1] * s
    logo_h = 1000
    logo_img = recolor(resize(logo, (round(logo.width * logo_h / logo.height), logo_h)), WHITE)
    ratio = logo_h / (LOGO_BOX[3] - LOGO_BOX[1])  # from KEVbox.png pixels to this drawing
    letters_top = round((BOX_LETTERS_TOP - LOGO_BOX[1]) * ratio)
    letters_bottom = round((BOX_LETTERS_BOTTOM - LOGO_BOX[1]) * ratio)
    cap_h = letters_bottom - letters_top
    probe = font(1000)
    probe_cap = -probe.getbbox("LIVE", anchor="ls")[1]
    f = font(round(1000 * cap_h / probe_cap))
    left, _, right, _ = f.getbbox("LIVE", anchor="ls")
    gap = round(logo_h * 0.12)
    full_w = logo_img.width + gap + (right - left)
    kevbox = Image.new("RGBA", (full_w, logo_h), WHITE + (0,))
    kevbox.alpha_composite(logo_img, (0, 0))
    live = Image.new("RGBA", (full_w, logo_h), WHITE + (0,))
    ImageDraw.Draw(live).text(
        (logo_img.width + gap - left, letters_bottom), "LIVE", font=f, fill=WHITE + (255,), anchor="ls"
    )
    return fit_into(kevbox, (box_w, box_h)), fit_into(live, (box_w, box_h))


def build_masters() -> None:
    logo, cube = load_logo()
    # Work from a smaller copy: the source is 6353 px wide and every output is far smaller.
    small_w = 3200
    ratio = small_w / logo.width
    logo = resize(logo, (small_w, round(logo.height * ratio)))
    cube = resize(cube, (round(cube.width * ratio), round(cube.height * ratio)))
    save_png(build_mark_master(cube), MARK)
    save_png(build_banner_master(logo), BANNER)
    save_png(build_splash_name_master(logo), SPLASH_NAME)
    kevbox, live = build_wordmark_masters(logo)
    save_png(kevbox, WORDMARK_KEVBOX)
    save_png(live, WORDMARK_LIVE)
    print(f"rebrand-art: masters written to {ART.relative_to(REPO)}")


# ---------------------------------------------------------------------------------------------
# Core brand files


def brand_files(core_res: Path) -> list[tuple[str, str, Path]]:
    """(qualifier, name, path) for every Core brand drawable, sorted."""
    found = []
    for qdir in sorted(p for p in core_res.iterdir() if p.is_dir()):
        if qdir.name.startswith("values"):
            continue  # owntv_icon_colors*.xml there are colour values, not drawables
        for f in sorted(qdir.iterdir()):
            name = f.name.split(".", 1)[0]
            if BRAND_NAME.match(name):
                found.append((qdir.name, name, f))
    return found


def role(qualifier: str, name: str, path: Path) -> str:
    raster = path.suffix in (".png", ".webp", ".jpg")
    if name in ("owntv_mark_play", "owntv_mark_play_small"):
        return "empty"
    if name == "owntv_wordmark_own":
        return "wordmark_kevbox"
    if name == "owntv_wordmark_tv":
        return "wordmark_live"
    if name == "owntv_notification":
        return "notification"
    if name == "owntv_icon_monochrome":
        return "monochrome"
    if name.startswith("owntv_icon_") and name.endswith("_foreground") and raster:
        return "icon_foreground"
    if name.startswith("owntv_icon_") and qualifier.startswith("mipmap-anydpi"):
        return "adaptive"
    if name.startswith("owntv_banner_") and raster:
        return "banner"
    if name.startswith("owntv_splash_name_") and raster:
        return "splash_name"
    if name.startswith("owntv_splash_") and not raster:
        return "splash_icon"
    if name.startswith("owntv_mark_small_") and not raster:
        return "mark_small"
    if name.startswith("owntv_mark_") and not raster:
        return "mark"
    sys.exit(f"rebrand-art: no rule for Core brand file {qualifier}/{path.name}; add one")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_override(out_dir: Path, name: str, ext: str, write) -> None:
    """Write out_dir/name.ext and drop an override of the same name with another extension."""
    for old in out_dir.glob(f"{name}.*"):
        if old.suffix != f".{ext}":
            old.unlink()
    write(out_dir / f"{name}.{ext}")


def bitmap_xml(name: str) -> str:
    note = GENERATED_NOTE.format(what=f"Replaces Core's {name} with KevBox Live art.")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{note}\n"
        '<bitmap xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:src="@drawable/kevbox_{name}"\n'
        '    android:gravity="fill"\n'
        '    android:filter="true" />\n'
    )


def empty_vector_xml(name: str, core_xml: Path) -> str:
    sizes = dict(VECTOR_SIZE.findall(core_xml.read_text(encoding="utf-8")))
    note = GENERATED_NOTE.format(
        what=f"Empty on purpose: the KevBox mark has no play triangle for {name} to tint."
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{note}\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{sizes["width"]}" android:height="{sizes["height"]}"\n'
        f'    android:viewportWidth="{sizes["viewportWidth"]}"'
        f' android:viewportHeight="{sizes["viewportHeight"]}" />\n'
    )


def adaptive_xml(name: str) -> str:
    note = GENERATED_NOTE.format(what=f"Replaces Core's {name} with the KevBox Live icon.")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{note}\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/kevbox_icon_background"/>\n'
        f'    <foreground android:drawable="@mipmap/{name}_foreground"/>\n'
        '    <monochrome android:drawable="@drawable/owntv_icon_monochrome"/>\n'
        "</adaptive-icon>\n"
    )


ICON_BACKGROUND_XML = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    + GENERATED_NOTE.format(what="Background layer of the KevBox Live adaptive launcher icon.")
    + "\n"
    '<color xmlns:android="http://schemas.android.com/apk/res/android" android:color="#FFFFFFFF" />\n'
)


def load_masters() -> dict[str, Image.Image]:
    paths = {
        "mark": MARK,
        "banner": BANNER,
        "splash_name": SPLASH_NAME,
        "wordmark_kevbox": WORDMARK_KEVBOX,
        "wordmark_live": WORDMARK_LIVE,
    }
    missing = [p for p in paths.values() if not p.is_file()]
    if missing:
        sys.exit("rebrand-art: missing masters (run with --masters): " + ", ".join(map(str, missing)))
    return {key: Image.open(p).convert("RGBA") for key, p in paths.items()}


def generate(core_res: Path) -> int:
    m = load_masters()
    mark_sil = silhouette(m["mark"])
    nodpi = RES / "drawable-nodpi"
    count = 0
    for qualifier, name, path in brand_files(core_res):
        kind = role(qualifier, name, path)
        out_dir = RES / qualifier
        if kind in ("icon_foreground", "banner", "splash_name"):
            size = Image.open(path).size
            if kind == "icon_foreground":
                img = fit_into(m["mark"], size, ICON_SCALE)
            elif kind == "banner":
                img = resize(m["banner"], size).convert("RGB")
            else:
                img = fit_into(m["splash_name"], size)
            write_override(out_dir, name, "png", lambda p, img=img: save_png(img, p))
        elif kind in ("mark", "mark_small"):
            px = MARK_PX if kind == "mark" else MARK_SMALL_PX
            img = resize(m["mark"], (px, px))
            write_override(out_dir, name, "png", lambda p, img=img: save_png(img, p))
        elif kind in ("wordmark_kevbox", "wordmark_live"):
            img = resize(m[kind], WORDMARK_PX)
            write_override(out_dir, name, "png", lambda p, img=img: save_png(img, p))
        elif kind in ("splash_icon", "notification", "monochrome"):
            if kind == "splash_icon":
                raster = fit_into(m["mark"], (SPLASH_ICON_PX,) * 2, SPLASH_SCALE)
            elif kind == "notification":
                raster = fit_into(mark_sil, (NOTIFICATION_PX,) * 2, NOTIFICATION_SCALE)
            else:
                raster = fit_into(mark_sil, (MONOCHROME_PX,) * 2, ICON_SCALE)
            save_png(raster, nodpi / f"kevbox_{name}.png")
            write_override(out_dir, name, "xml", lambda p, n=name: write_text(p, bitmap_xml(n)))
        elif kind == "empty":
            text = empty_vector_xml(name, path)
            write_override(out_dir, name, "xml", lambda p, t=text: write_text(p, t))
        elif kind == "adaptive":
            write_override(out_dir, name, "xml", lambda p, n=name: write_text(p, adaptive_xml(n)))
        count += 1
    write_text(RES / "drawable" / "kevbox_icon_background.xml", ICON_BACKGROUND_XML)
    return count


def check(core_res: Path) -> int:
    files = brand_files(core_res)
    missing = []
    for qualifier, name, path in files:
        role(qualifier, name, path)  # stops on a brand file no rule covers
        overrides = sorted((RES / qualifier).glob(f"{name}.*"))
        if not overrides:
            missing.append(f"{qualifier}/{name}")
            continue
        for override in overrides:
            if override.suffix != ".xml":
                continue
            ref = re.search(r'android:src="@drawable/([a-z0-9_]+)"', override.read_text(encoding="utf-8"))
            if ref and not list((RES / "drawable-nodpi").glob(f"{ref.group(1)}.*")):
                missing.append(f"drawable-nodpi/{ref.group(1)} (used by {qualifier}/{name})")
    if not (RES / "drawable" / "kevbox_icon_background.xml").is_file():
        missing.append("drawable/kevbox_icon_background (adaptive icon background)")
    for line in missing:
        print(f"missing: {line}")
    if missing:
        print(f"rebrand-art: {len(missing)} missing; run python3 tools/kevbox/rebrand-art.py")
        return 1
    print(f"rebrand-art: all {len(files)} Core brand files have a KevBox override")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="exit 1 if a Core brand file lacks an override")
    group.add_argument("--masters", action="store_true", help="rebuild the masters from the logo, then regenerate")
    args = parser.parse_args()
    core_res = core_res_dir(REPO)
    if args.check:
        return check(core_res)
    if args.masters:
        build_masters()
    count = generate(core_res)
    print(f"rebrand-art: {count} overrides written for Core {core_pin(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
